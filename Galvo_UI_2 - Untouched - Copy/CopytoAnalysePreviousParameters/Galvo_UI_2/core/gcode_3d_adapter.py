
"""
G-Code 3D Toolpath Adapter for Galvo Laser Systems.
==================================================
Reads, analyzes, and adapts sliced 3D G-code files (OrcaSlicer, Cura, PrusaSlicer, Bambu, etc.)
for multi-layer Galvo laser bas-relief and deep engraving.
"""

import os
import re
import time


class GCode3DAdapter:
    """
    Ingests FDM/Laser sliced G-code files, centers them, scales them to the Galvo field,
    and converts them into native Galvo 16-bit Jump & Mark vector queues.
    """
    def __init__(
        self,
        gcode_path: str,
        field_size: float = 100.0,
        target_diameter_mm: float = None,
        auto_center: bool = True,
        ignore_skirts: bool = True,
        mark_speed_mms: float = 800.0,
        jump_speed_mms: float = 2000.0,
        laser_power: float = None,
        laser_freq: float = None,
        target_passes: int = None,
        offset_x_mm: float = 0.0,
        offset_y_mm: float = 0.0
    ):
        self.gcode_path = os.path.abspath(gcode_path)
        self.field_size = float(field_size)
        self.target_diameter_mm = float(target_diameter_mm) if target_diameter_mm else None
        self.auto_center = auto_center
        self.ignore_skirts = ignore_skirts
        self.target_passes = int(target_passes) if target_passes and int(target_passes) > 0 else None
        self.offset_x_mm = float(offset_x_mm)
        self.offset_y_mm = float(offset_y_mm)
        
        self.galvo_units_per_mm = 65535.0 / self.field_size
        self.center_bits = 32767.5

        self.mark_speed_mms = float(mark_speed_mms)
        self.jump_speed_mms = float(jump_speed_mms)
        self.mark_speed_gu = int(round(self.mark_speed_mms * self.galvo_units_per_mm))
        self.jump_speed_gu = int(round(self.jump_speed_mms * self.galvo_units_per_mm))
        self.laser_power = laser_power
        self.laser_freq = laser_freq
        
        self.raw_layers = []
        self.layers = []
        self.metadata = {}
        self.bounding_box = {}
        self.scale_factor = 1.0
        
        self.parse_and_adapt()

    def parse_and_adapt(self):
        if not os.path.exists(self.gcode_path):
            raise FileNotFoundError(f"G-code file not found: {self.gcode_path}")

        t0 = time.time()
        
        # Pre-scan for file format characteristics (FDM vs Laser/CNC G-code)
        has_e_moves = False
        has_orca_markers = False
        with open(self.gcode_path, 'r', encoding='utf-8', errors='ignore') as f:
            for i, line in enumerate(f):
                if i > 5000:
                    break
                l = line.strip()
                if '; printing object' in l or ';TYPE:' in l or ';LAYER:0' in l or ';LAYER_CHANGE' in l:
                    has_orca_markers = True
                if re.search(r'E[-+]?[0-9]*\.?[0-9]+', l):
                    has_e_moves = True

        is_laser_gcode = not has_e_moves

        # 1. Pass 1: Extract header metadata & compute exact model bounding box
        min_x, max_x = float('inf'), float('-inf')
        min_y, max_y = float('inf'), float('-inf')
        min_z, max_z = float('inf'), float('-inf')
        
        curr_type = None
        has_started_model = not has_orca_markers
        curr_x, curr_y = None, None
        
        with open(self.gcode_path, 'r', encoding='utf-8', errors='ignore') as f:
            for line in f:
                l = line.strip()
                if not l:
                    continue
                if l.startswith('; generated by'):
                    self.metadata['slicer'] = l.replace('; generated by', '').strip()
                elif l.startswith('; total layer number:'):
                    self.metadata['total_layers'] = int(l.split(':')[1].strip())
                elif l.startswith('; max_z_height:'):
                    self.metadata['max_z'] = float(l.split(':')[1].strip())
                elif '; printing object' in l:
                    has_started_model = True
                    curr_type = 'Model'
                elif '; stop printing object' in l:
                    has_started_model = False
                    curr_type = 'Custom'
                elif l.startswith(';LAYER:0') or l.startswith(';LAYER:1'):
                    has_started_model = True
                elif l.startswith(';TYPE:'):
                    curr_type = l.split(':')[1].strip()
                    if curr_type not in ['Custom', 'Skirt', 'Brim']:
                        has_started_model = True
                elif l.startswith(('G1 ', 'G0 ', 'G1', 'G0', 'G2', 'G3')):
                    if not has_started_model and self.ignore_skirts:
                        continue
                    if has_orca_markers and self.ignore_skirts and curr_type in ['Custom', 'Skirt', 'Brim']:
                        continue
                        
                    m_x = re.search(r'X([-+]?[0-9]*\.?[0-9]+)', l)
                    m_y = re.search(r'Y([-+]?[0-9]*\.?[0-9]+)', l)
                    m_z = re.search(r'Z([-+]?[0-9]*\.?[0-9]+)', l)
                    m_e = re.search(r'E([-+]?[0-9]*\.?[0-9]+)', l)
                    
                    if m_z:
                        z = float(m_z.group(1))
                        min_z = min(min_z, z)
                        max_z = max(max_z, z)
                    if m_x:
                        curr_x = float(m_x.group(1))
                    if m_y:
                        curr_y = float(m_y.group(1))

                    if curr_x is not None and curr_y is not None:
                        if is_laser_gcode:
                            min_x = min(min_x, curr_x)
                            max_x = max(max_x, curr_x)
                            min_y = min(min_y, curr_y)
                            max_y = max(max_y, curr_y)
                        else:
                            is_ext = (m_e is not None and float(m_e.group(1)) > 0)
                            if is_ext or curr_y > 10.0:
                                min_x = min(min_x, curr_x)
                                max_x = max(max_x, curr_x)
                                min_y = min(min_y, curr_y)
                                max_y = max(max_y, curr_y)

        if min_x == float('inf'):
            min_x, max_x = 0.0, 50.0
            min_y, max_y = 0.0, 50.0

        model_w = max(0.1, max_x - min_x)
        model_h = max(0.1, max_y - min_y)
        model_d = max(model_w, model_h)
        cx = (min_x + max_x) / 2.0
        cy = (min_y + max_y) / 2.0

        self.bounding_box = {
            'min_x': min_x, 'max_x': max_x, 'width': model_w,
            'min_y': min_y, 'max_y': max_y, 'height': model_h,
            'min_z': min_z, 'max_z': max_z,
            'center_x': cx, 'center_y': cy,
            'model_diameter': model_d
        }

        # 2. Determine Scale Factor
        if self.target_diameter_mm and self.target_diameter_mm > 0:
            self.scale_factor = self.target_diameter_mm / model_d
        elif model_d > (self.field_size * 0.92):
            # Scale down to fit comfortably in Galvo marking field
            self.scale_factor = (self.field_size * 0.90) / model_d
        else:
            self.scale_factor = 1.0

        # 3. Pass 2: Extract Layers and Convert to Galvo Vectors
        layers_dict = {}  # layer_idx -> layer_data
        curr_layer_idx = 1
        curr_z = 0.0
        curr_type = None
        has_started_model = not has_orca_markers
        raw_x, raw_y = None, None

        with open(self.gcode_path, 'r', encoding='utf-8', errors='ignore') as f:
            for line in f:
                l = line.strip()
                if not l:
                    continue

                # Layer boundary detection across Orca, Bambu, Cura, Prusa vs Laser/CNC G-code
                if l.startswith(';Z:') or l.startswith(';LAYER:'):
                    val = l.split(':')[1].strip()
                    try:
                        if l.startswith(';Z:'):
                            curr_z = float(val)
                        else:
                            parsed_idx = int(val) + 1
                            if parsed_idx > curr_layer_idx:
                                curr_layer_idx = parsed_idx
                    except ValueError:
                        pass
                elif l.startswith(';LAYER_CHANGE'):
                    if curr_layer_idx in layers_dict and layers_dict[curr_layer_idx]['commands']:
                        curr_layer_idx += 1
                elif '; printing object' in l:
                    has_started_model = True
                    curr_type = 'Model'
                elif '; stop printing object' in l:
                    has_started_model = False
                    curr_type = 'Custom'
                elif l.startswith(';LAYER:0') or l.startswith(';LAYER:1'):
                    has_started_model = True
                elif l.startswith(';TYPE:'):
                    curr_type = l.split(':')[1].strip()
                    if curr_type not in ['Custom', 'Skirt', 'Brim']:
                        has_started_model = True
                elif not has_orca_markers and l.startswith(';'):
                    # Laser / CNC pass detection: ; Pass 1/20, ; Layer 1/50, ; 3d_layer: 1, etc.
                    m_pass = re.search(r'(?:layer|pass|slice|3d_layer)\s*[:#]?\s*(\d+)', l, re.IGNORECASE)
                    if m_pass:
                        has_started_model = True
                        if curr_layer_idx in layers_dict and layers_dict[curr_layer_idx]['commands']:
                            curr_layer_idx += 1

                elif l.startswith(('G1 ', 'G0 ', 'G1', 'G0', 'G2', 'G3')):
                    if not has_started_model and self.ignore_skirts:
                        continue
                    if has_orca_markers and self.ignore_skirts and curr_type in ['Custom', 'Skirt', 'Brim']:
                        continue

                    m_x = re.search(r'X([-+]?[0-9]*\.?[0-9]+)', l)
                    m_y = re.search(r'Y([-+]?[0-9]*\.?[0-9]+)', l)
                    m_z = re.search(r'Z([-+]?[0-9]*\.?[0-9]+)', l)
                    m_e = re.search(r'E([-+]?[0-9]*\.?[0-9]+)', l)
                    m_s = re.search(r'S([-+]?[0-9]*\.?[0-9]+)', l)

                    if m_z:
                        curr_z = float(m_z.group(1))

                    if m_x:
                        raw_x = float(m_x.group(1))
                    if m_y:
                        raw_y = float(m_y.group(1))

                    if raw_x is not None and raw_y is not None:
                        # Center at (0, 0) and scale
                        if self.auto_center:
                            x_mm = (raw_x - cx) * self.scale_factor + self.offset_x_mm
                            y_mm = (raw_y - cy) * self.scale_factor + self.offset_y_mm
                        else:
                            x_mm = raw_x * self.scale_factor + self.offset_x_mm
                            y_mm = raw_y * self.scale_factor + self.offset_y_mm

                        gx = int(round(self.center_bits + (x_mm * self.galvo_units_per_mm)))
                        gy = int(round(self.center_bits + (y_mm * self.galvo_units_per_mm)))

                        # Clamped to 16-bit DAC
                        gx_clamped = max(0, min(65535, gx))
                        gy_clamped = max(0, min(65535, gy))

                        # Determine if move is mark or jump
                        if is_laser_gcode:
                            is_g0 = l.startswith(('G0 ', 'G0'))
                            s_val = float(m_s.group(1)) if m_s else None
                            if is_g0:
                                cmd_type = 'jump'
                            elif s_val is not None:
                                cmd_type = 'mark' if s_val > 0 else 'jump'
                            else:
                                cmd_type = 'mark'
                        else:
                            is_extruding = (m_e is not None and float(m_e.group(1)) > 0)
                            cmd_type = 'mark' if is_extruding else 'jump'

                        cmd_speed = self.mark_speed_gu if cmd_type == 'mark' else self.jump_speed_gu

                        if curr_layer_idx not in layers_dict:
                            layers_dict[curr_layer_idx] = {
                                'layer_num': curr_layer_idx,
                                'z': curr_z,
                                'depth_mm': curr_z,
                                'angle_deg': 0.0,
                                'commands': []
                            }

                        layer_cmds = layers_dict[curr_layer_idx]['commands']

                        # Safety: If the first command in a layer is a mark, prepend a jump
                        # so the laser never turns on and marks across the bed from an unknown position.
                        if cmd_type == 'mark' and not layer_cmds:
                            layer_cmds.append({
                                'type': 'jump',
                                'x': gx_clamped,
                                'y': gy_clamped,
                                'speed': self.jump_speed_gu,
                                'x_mm': x_mm,
                                'y_mm': y_mm
                            })

                        cmd_dict = {
                            'type': cmd_type,
                            'x': gx_clamped,
                            'y': gy_clamped,
                            'speed': cmd_speed,
                            'x_mm': x_mm,
                            'y_mm': y_mm
                        }
                        if cmd_type == 'mark':
                            if self.laser_power is not None:
                                cmd_dict['power'] = self.laser_power
                            if self.laser_freq is not None:
                                cmd_dict['freq'] = self.laser_freq

                        layer_cmds.append(cmd_dict)

        # Filter out empty layers and sort sequentially
        valid_layers = [l for idx, l in sorted(layers_dict.items()) if l['commands']]
        for i, lyr in enumerate(valid_layers):
            lyr['layer_num'] = i + 1

        self.raw_layers = valid_layers
        self._adapt_layers(self.target_passes)

        elapsed = time.time() - t0
        
        print(f"[GCode3DAdapter] Adapted '{os.path.basename(self.gcode_path)}' in {elapsed:.2f}s:")
        print(f"  Raw Slices: {len(self.raw_layers)} -> Laser Passes: {len(self.layers)} | Slicer: {self.metadata.get('slicer', 'Unknown')}")
        print(f"  Model Size: {model_w:.1f}x{model_h:.1f}mm -> Scaled: {model_w*self.scale_factor:.1f}x{model_h*self.scale_factor:.1f}mm (Scale: {self.scale_factor:.3f})")
        print(f"  Mark Speed: {self.mark_speed_mms} mm/s ({self.mark_speed_gu} bits/s) | Jump Speed: {self.jump_speed_mms} mm/s ({self.jump_speed_gu} bits/s)")
        print(f"  Total Vectors: {sum(len(l['commands']) for l in self.layers)}")

    def _adapt_layers(self, target_passes: int = None):
        """
        Maps raw sliced layers (e.g. 64) to the target number of laser engraving passes (e.g. 500).
        Evenly distributes raw slices across passes preserving model topology from top to bottom.
        """
        if target_passes and int(target_passes) > 0:
            self.target_passes = int(target_passes)

        N = len(self.raw_layers)
        if N == 0:
            self.layers = []
            return

        P = self.target_passes if (self.target_passes and self.target_passes > 0) else N
        self.target_passes = P

        min_z = self.raw_layers[0].get('z', 0.0)
        max_z = self.raw_layers[-1].get('z', 0.0)

        adapted_layers = []
        for p in range(1, P + 1):
            if N == 1 or P == 1:
                s_idx = 0
                t = 0.0
            else:
                t = (p - 1) / (P - 1)
                s_idx = min(N - 1, max(0, int(round(t * (N - 1)))))

            raw_lyr = self.raw_layers[s_idx]
            z_interp = min_z + t * (max_z - min_z)

            adapted_layers.append({
                'layer_num': p,
                'raw_slice_idx': s_idx + 1,
                'total_raw_slices': N,
                'z': z_interp,
                'depth_mm': z_interp,
                'angle_deg': 0.0,
                'commands': raw_lyr['commands']
            })

        self.layers = adapted_layers

    def compile_job_queue(
        self,
        mark_speed_mms: float = None,
        jump_speed_mms: float = None,
        laser_power: float = None,
        laser_freq: float = None,
        clean_interval: int = 0,
        target_passes: int = None
    ):
        """Compiles the complete Galvo execution queue with real-time layer progress markers."""
        if target_passes and int(target_passes) > 0 and int(target_passes) != len(self.layers):
            self._adapt_layers(target_passes)

        if mark_speed_mms is not None:
            self.mark_speed_mms = float(mark_speed_mms)
            self.mark_speed_gu = int(round(self.mark_speed_mms * self.galvo_units_per_mm))
        if jump_speed_mms is not None:
            self.jump_speed_mms = float(jump_speed_mms)
            self.jump_speed_gu = int(round(self.jump_speed_mms * self.galvo_units_per_mm))
        if laser_power is not None:
            self.laser_power = float(laser_power)
        if laser_freq is not None:
            self.laser_freq = float(laser_freq)

        queue = []
        total_layers = len(self.layers)

        for idx, layer in enumerate(self.layers):
            layer_num = idx + 1
            z_val = layer.get('z', 0.0)
            raw_idx = layer.get('raw_slice_idx', layer_num)

            # Insert pass_change event for galvo_controller execution & real-time progress callback
            queue.append({
                'type': 'pass_change',
                'layer_idx': layer_num,
                'total_layers': total_layers,
                'depth_mm': z_val,
                'angle_deg': 0.0,
                'desc': f"Pass {layer_num}/{total_layers} (Raw Slice {raw_idx})"
            })

            # Also insert live layer tracking comment tag
            queue.append({
                'type': 'comment',
                'text': f"; 3d_layer: {layer_num} / {total_layers} (depth: {z_val:.3f} mm, raw_slice: {raw_idx})"
            })

            # Append layer commands with verified speeds
            need_override = (mark_speed_mms is not None or jump_speed_mms is not None or laser_power is not None or laser_freq is not None)
            if need_override:
                for cmd in layer['commands']:
                    c = dict(cmd)
                    if c.get('type') == 'mark':
                        c['speed'] = self.mark_speed_gu
                        if self.laser_power is not None:
                            c['power'] = self.laser_power
                        if self.laser_freq is not None:
                            c['freq'] = self.laser_freq
                    elif c.get('type') == 'jump':
                        c['speed'] = self.jump_speed_gu
                    queue.append(c)
            else:
                queue.extend(layer['commands'])

            # Clean pass if clean_interval > 0
            if clean_interval > 0 and (layer_num % clean_interval == 0) and layer_num < total_layers:
                queue.append({
                    'type': 'comment',
                    'text': f"; 3d_clean: interval {clean_interval}"
                })

        return queue
